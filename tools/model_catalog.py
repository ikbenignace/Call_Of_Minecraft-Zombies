#!/usr/bin/env python3
"""Writes resourcepack/MODEL_CATALOG.md: every gun in guns.json, the model it renders with, whether
that model is a real 3D model or a flat sprite, which guns share it, and its review status from
resourcepack/model-registry.json.

Usage: python3 tools/model_catalog.py
"""
import collections
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, 'resourcepack/comz-pack/assets')
GUNS = os.path.join(ROOT, 'Core/src/main/resources/guns.json')
REGISTRY = os.path.join(ROOT, 'resourcepack/model-registry.json')
OUT = os.path.join(ROOT, 'resourcepack/MODEL_CATALOG.md')
GUN_MODEL_DIR = 'custom/item/3d_guns/'


def item_model_target(key):
    ns, path = key.split(':', 1)
    item_def = os.path.join(ASSETS, ns, 'items', path + '.json')
    if not os.path.exists(item_def):
        return None
    return json.load(open(item_def))['model']['model']


def model_info(model):
    ns, path = model.split(':', 1) if ':' in model else ('minecraft', model)
    f = os.path.join(ASSETS, ns, 'models', path + '.json')
    if not os.path.exists(f):
        return None
    data = json.load(open(f))
    return len(data.get('elements', []))


def main():
    guns = json.load(open(GUNS))
    registry = json.load(open(REGISTRY))['models']
    rows = []
    for category, entry in guns.items():
        for gun in entry['guns']:
            for tier, g in (('base', gun), ('PaP', gun.get('pack_a_punch_gun'))):
                if g and g.get('item_model'):
                    model = item_model_target(g['item_model'])
                    rows.append((category.replace('_', ' '), gun['name'], tier, g['name'], g['item_model'], model))

    users = collections.defaultdict(list)
    for r in rows:
        if r[5]:
            users[r[5]].append(r[4].split('/')[-1])

    lines = ['# Gun model catalog', '',
             'Generated by `tools/model_catalog.py` from `guns.json`, the pack and `model-registry.json`. '
             'Do not edit by hand; update the registry and re-run.', '',
             '| Category | Gun | Tier | In-game name | Model | Kind | Shared with | Origin | Status |',
             '|---|---|---|---|---|---|---|---|---|']
    for category, base, tier, name, key, model in rows:
        if model is None:
            lines.append('| %s | %s | %s | %s | — | missing item-def | | | |' % (category, base, tier, name))
            continue
        elements = model_info(model)
        short = model.replace('minecraft:custom/item/', '')
        kind = 'missing model' if elements is None else ('2D sprite' if elements == 0 else '3D (%d el)' % elements)
        shared = [u for u in users[model] if u != key.split('/')[-1]]
        reg = registry.get(model.split(GUN_MODEL_DIR, 1)[1], {}) if GUN_MODEL_DIR in model else {}
        lines.append('| %s | %s | %s | %s | `%s` | %s | %s | %s | %s |' % (
            category, base, tier, name, short, kind, ', '.join(shared) or '', reg.get('origin', ''), reg.get('status', '')))

    base_rows = [r for r in rows if r[2] == 'base']
    own_3d = [r for r in base_rows if r[5] and len(users[r[5]]) == 1 and (model_info(r[5]) or 0) > 0]
    pap_3d = [r for r in rows if r[2] == 'PaP' and r[5] and (model_info(r[5]) or 0) > 0]
    by_status = collections.Counter(v.get('status') for v in registry.values())
    lines += ['', '## Summary', '',
              '- Guns: %d (each with a Pack-a-Punch variant)' % len(base_rows),
              '- Base guns with their own 3D model: %d' % len(own_3d),
              '- Base guns sharing one model with another gun (stand-ins; M1911 is the genuine owner of m1911_v2): %s' % ', '.join(r[1] for r in base_rows if r[5] and len(users[r[5]]) > 1),
              '- PaP variants with a 3D model: %d of %d (the rest are 2D sprites)' % (len(pap_3d), len(rows) - len(base_rows)),
              '- Registry status: %s' % ', '.join('%s %d' % kv for kv in sorted(by_status.items()))]
    open(OUT, 'w').write('\n'.join(lines) + '\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
